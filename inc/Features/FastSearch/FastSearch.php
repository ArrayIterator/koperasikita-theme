use function is_array;
use function trim;
use function update_option;
use function wp_nonce_field;

/**
 * Fast Search — frontend search sped up with database indexes.
 *
 * The design follows the TrayDigita Core Fast Search module: a
 * FULLTEXT index on wp_posts (post_title, post_content,
 * post_excerpt), a FULLTEXT index on wp_terms.name, and join
 * indexes on the term relationship / taxonomy tables. The
 * post-type/status/date filtering is served by WordPress core's
 * own `type_status_date` index on wp_posts — it is deliberately
 * NOT redefined here. The frontend search then runs
 * `MATCH ... AGAINST (... IN BOOLEAN MODE)` (words cleaned of
 * boolean operators, minimum two characters, `+word*` tokens)
 * and also matches posts through their category / tag names.
 *
 * While the FULLTEXT indexes are missing, the module is a safe
 * no-op: the standard WordPress search runs untouched, so search
 * never breaks and never returns empty results because of a
 * missing index. Index builds run from the Setup page, one index
 * per AJAX request behind a transient lock (see IndexManager /
 * FastSearchAjax), inside a popup that shows the progress.
 * Index builds never run on a frontend request.
 *
 * There is no live search here, by design: no as-you-type
 * dropdown, no frontend AJAX search endpoint. The header field
 * submits the form to the full results page, as before; the
 * index only makes that page's query fast.
 *
 * Settings live in the single option `kk_fast_search`
 * (autoload `no`): `fulltext_search` (use the FULLTEXT search
 * once the indexes are ready) and `limit_to_posts` (frontend
 * search covers posts only). Both default to on.
 */
final class FastSearch
{
    /**
     * Option name for all Fast Search settings (autoload `no`).
     */
    public const string OPTION = 'kk_fast_search';

    /**
     * Nonce action for the behaviour settings form.
     */
    public const string SAVE_NONCE_ACTION = 'kk_fast_search_save';

    /**
     * Register the module hooks.
     *
     * Registers the frontend search hooks (`pre_get_posts` to
     * limit search to posts, `posts_search` for the FULLTEXT
     * clause) and the chunked index-build AJAX endpoints. Each
     * frontend callback re-checks the settings and the cached
     * ready flag at run time, so disabling the search or losing
     * the indexes takes effect immediately.
     *
     * @return void
     */
    public static function register(): void
    {
        add_action('pre_get_posts', [self::class, 'optimizeSearchQuery']);
        add_filter('posts_search', [self::class, 'filterPostsSearch'], 10, 2);
        FastSearchAjax::register();
    }

    /**
     * Limit frontend search queries to posts.
     *
     * Only the main frontend search query is touched, and only
     * when no post type was requested explicitly: a search that
     * already asks for pages or a custom post type keeps exactly
     * what it asked for. Admin queries are never touched.
     *
     * @param WP_Query $query The query being prepared.
     * @return void
     */
    public static function optimizeSearchQuery(WP_Query $query): void
    {
        if (is_admin() || !$query->is_main_query() || !$query->is_search()) {
            return;
        }
        if (!self::getSettings()['limit_to_posts']) {
            return;
        }
        if (empty($query->get('post_type'))) {
            $query->set('post_type', ['post']);
        }
    }

    /**
     * Replace the search SQL with a FULLTEXT MATCH clause.
     *
     * Returns the original `$search` untouched whenever the fast
     * search cannot or should not run: the FULLTEXT toggle is off,
     * the indexes are not ready, the request is in the admin, the
     * query is not the main frontend search, the search string is
     * empty, or nothing usable remains after cleaning it. That
     * fallback is what keeps search working (standard WordPress
     * LIKE search) while the indexes are missing.
     *
     * When it runs, the clause is a MATCH ... AGAINST in boolean
     * mode over the posts FULLTEXT index, OR-ed with posts whose
     * category or tag name matched (capped at 500 ids).
     *
     * @param string $search Search SQL generated by WordPress.
     * @param WP_Query $query The query being prepared.
     * @return string Replacement search SQL, or the original.
     */
    public static function filterPostsSearch(string $search, WP_Query $query): string
    {
        if (!self::getSettings()['fulltext_search']) {
            return $search;
        }
        if (!IndexManager::isReady()) {
            return $search;
        }
        if ($search === '' || is_admin() || !$query->is_search() || !$query->is_main_query()) {
            return $search;
        }
        $rawTerm = trim((string) $query->get('s'));
        if ($rawTerm === '') {
            return $search;
        }
        $booleanQuery = QueryBuilder::buildBooleanQuery($rawTerm);
        if ($booleanQuery === '') {
            return $search;
        }
        global $wpdb;
        return QueryBuilder::buildSearchClause($wpdb, $booleanQuery);
    }

    /**
     * Read the stored settings merged over the defaults.
     *
     * @return array{fulltext_search: bool, limit_to_posts: bool}
     */
    public static function getSettings(): array
    {
        $stored = get_option(self::OPTION, []);
        if (!is_array($stored)) {
            $stored = [];
        }
        $settings = array_merge(self::getDefaults(), $stored);
        return [
            'fulltext_search' => (bool) ($settings['fulltext_search'] ?? true),
            'limit_to_posts' => (bool) ($settings['limit_to_posts'] ?? true),
        ];
    }

    /**
     * Default settings.
     *
     * Both the FULLTEXT search and the posts-only limit are on:
     * with the indexes installed this is the fast path, and
     * without them the module falls back silently.
     *
     * @return array{fulltext_search: bool, limit_to_posts: bool}
     */
    public static function getDefaults(): array
    {
        return [
            'fulltext_search' => true,
            'limit_to_posts' => true,
        ];
    }

    /**
     * Validate and save settings from a submitted form.
     *
     * Expected flat keys in `$data`: `fulltext_search`,
     * `limit_to_posts` (each `1` when checked; the form always
     * submits a hidden `0` first, so an unchecked box arrives as
     * `0`). Every value is cast to boolean explicitly. Unknown
     * keys are dropped.
     *
     * @param array<string, mixed> $data Form data (unslashed).
     * @return array{success: bool, message: string}
     */
    public static function saveSettings(array $data): array
    {
        if (!current_user_can('manage_options')) {
            return [
                'success' => false,
                'message' => __('You are not allowed to change Fast Search settings.', 'koperasikita'),
            ];
        }
        $settings = [
            'fulltext_search' => !empty($data['fulltext_search']),
            'limit_to_posts' => !empty($data['limit_to_posts']),
        ];
        update_option(self::OPTION, $settings, false);
        return [
            'success' => true,
            'message' => __('Fast Search settings saved.', 'koperasikita'),
        ];
    }

    /**
     * Whether the FULLTEXT search is ready, from the cached flag.
     *
     * @return bool
     */
    public static function isReady(): bool
    {
        return IndexManager::isReady();
    }

    /**
     * Render the Fast Search section on the Setup page.
     *
     * One section: a short description, the ready state with the
     * index status table, and — while the indexes are missing —
     * the instructions (what is missing, with the SQL statements
     * for manual installation) plus the button that opens the
     * build popup. The behaviour toggles sit below, saved through
     * a plain admin-post form. The build itself never runs here:
     * the popup (admin.ts initFastSearchBuild) starts it, one
     * index per AJAX request, and shows the progress inside the
     * popup until it finishes.
     *
     * @return void
     */
    public static function renderSetupCard(): void
    {
        $settings = self::getSettings();
        $definitions = IndexManager::definitions();
        $statuses = IndexManager::checkStatus();
        $ready = IndexManager::isReady();
        $missingSql = [];
        foreach ($definitions as $key => $definition) {
            if (empty($statuses[$key])) {
                $missingSql[] = $definition['sql'];
            }
        }
        $missingSqlText = implode("\n", $missingSql);
        $job = IndexManager::jobProgress();

        echo '<section class="kk-setup-card" data-kk-fast-search>';
        echo '<div class="kk-setup-fast-search-card-head"><h2 class="kk-setup-card-title">' . esc_html__('Fast Search', 'koperasikita') . '</h2>'
            . '<button type="button" class="button" data-kk-fast-search-build' . disabled($job !== null, true, false) . '>'
            . esc_html__('Build indexes', 'koperasikita') . '</button></div>';
        echo '<div class="kk-setup-card-body">';
        echo '<p>' . esc_html__('Speed up frontend search with FULLTEXT and composite database indexes, with a safe fallback to standard WordPress search while the indexes are missing.', 'koperasikita') . '</p>';

        if ($ready) {
            echo '<p><span class="kk-setup-fast-search-badge kk-setup-fast-search-badge--ready">' . esc_html__('Active', 'koperasikita') . '</span> '
                . esc_html__('FULLTEXT search is active on frontend search queries.', 'koperasikita') . '</p>';
        } else {
            echo '<p><span class="kk-setup-fast-search-badge kk-setup-fast-search-badge--fallback">' . esc_html__('Fallback mode', 'koperasikita') . '</span> '
                . esc_html__('Required FULLTEXT indexes are missing. WordPress is safely using standard search until you install the indexes below.', 'koperasikita') . '</p>';
        }

        echo '<div class="kk-setup-fast-search-table-wrap">';
        echo '<table class="widefat striped kk-setup-fast-search-table">';
        echo '<thead><tr><th>' . esc_html__('Table', 'koperasikita') . '</th><th>' . esc_html__('Index name', 'koperasikita') . '</th><th>' . esc_html__('Type', 'koperasikita') . '</th><th>' . esc_html__('Columns', 'koperasikita') . '</th><th>' . esc_html__('Status', 'koperasikita') . '</th></tr></thead>';
        echo '<tbody>';
        foreach ($definitions as $key => $definition) {
            echo '<tr><td><code>' . esc_html($definition['table']) . '</code></td>';
            echo '<td><code>' . esc_html($definition['name']) . '</code></td>';
            echo '<td>' . esc_html($definition['type']) . '</td>';
            echo '<td><code>' . esc_html($definition['columns']) . '</code></td>';
            echo '<td data-kk-fast-search-row="' . esc_attr($key) . '">';
            if (!empty($statuses[$key])) {
                echo '<span class="kk-setup-fast-search-badge kk-setup-fast-search-badge--ready">' . esc_html__('Installed', 'koperasikita') . '</span>';
            } else {
                echo '<span class="kk-setup-fast-search-badge kk-setup-fast-search-badge--fallback">' . esc_html__('Missing', 'koperasikita') . '</span>';
            }
            echo '</td></tr>';
        }
        echo '</tbody></table>';
        echo '</div>';

        if ($job !== null) {
            echo '<p class="kk-setup-stack-status">' . esc_html__('An index build is already running. Wait for it to finish before starting another one.', 'koperasikita') . '</p>';
        }

        echo '<p class="kk-setup-fast-search-build"><span class="description">' . esc_html__('Installs the missing indexes one at a time. Large tables can take a while per index; the page stays responsive and shows progress in a popup.', 'koperasikita') . '</span></p>';

        if ($missingSqlText !== '') {
            echo '<p>' . esc_html__('Run these statements in the MariaDB / MySQL console to install the missing indexes manually, then reload this page.', 'koperasikita') . '</p>';
            echo '<textarea readonly rows="' . esc_attr((string) (count(explode("\n", $missingSqlText)) + 1)) . '" class="large-text code kk-setup-fast-search-sql">' . esc_textarea($missingSqlText) . '</textarea>';
        }

        echo '<form class="kk-setup-form" method="post" action="' . esc_url(admin_url('admin-post.php')) . '" data-kk-fast-search-settings>';
        echo '<input type="hidden" name="action" value="kk_fast_search_save">';
        wp_nonce_field(self::SAVE_NONCE_ACTION);
        echo '<p class="kk-setup-fast-search-check"><label><input type="hidden" name="fulltext_search" value="0"><input type="checkbox" name="fulltext_search" value="1"' . checked($settings['fulltext_search'], true, false) . '> '
            . esc_html__('Use FULLTEXT search', 'koperasikita') . '</label><br>'
            . '<span class="description">' . esc_html__('When on (and the indexes are installed), frontend search uses MATCH ... AGAINST in boolean mode, including matches on category and tag names. When off, or while the indexes are missing, standard WordPress search is used.', 'koperasikita') . '</span></p>';
        echo '<p class="kk-setup-fast-search-check"><label><input type="hidden" name="limit_to_posts" value="0"><input type="checkbox" name="limit_to_posts" value="1"' . checked($settings['limit_to_posts'], true, false) . '> '
            . esc_html__('Limit frontend search to posts', 'koperasikita') . '</label><br>'
            . '<span class="description">' . esc_html__('A search with no post type requested only searches posts, not pages or attachments. A search that explicitly asks for another post type is left alone.', 'koperasikita') . '</span></p>';
        echo '<button class="button button-primary" type="submit">' . esc_html__('Save settings', 'koperasikita') . '</button>';
        echo '</form>';

        echo '</div>';

        // The build popup: the same centered + blurred-backdrop
        // pattern as the gold sync popup (admin.css
        // .kk-data-desk-popup). The build starts when it opens and
        // the progress lives inside it; closing reloads the page
        // so the index status above shows the new state.
        ?>
        <div class="kk-data-desk-popup" id="kk-fast-search-popup" hidden role="dialog" aria-modal="true" aria-labelledby="kk-fast-search-popup-title">
            <div class="kk-data-desk-popup-backdrop" data-kk-fast-search-popup-close></div>
            <div class="kk-data-desk-popup-panel" role="document">
                <div class="kk-data-desk-popup-head">
                    <h2 id="kk-fast-search-popup-title"><?php esc_html_e('Build search indexes', 'koperasikita'); ?></h2>
                    <div class="kk-data-desk-popup-actions">
                        <button type="button" class="button" data-kk-fast-search-popup-close><?php esc_html_e('Close', 'koperasikita'); ?></button>
                    </div>
                </div>
                <div class="kk-data-desk-popup-body">
                    <p><progress data-kk-fast-search-bar max="100" value="0" style="width: 100%; max-width: 30rem;"></progress></p>
                    <p data-kk-fast-search-status role="status" aria-live="polite"></p>
                    <ul data-kk-fast-search-steps aria-live="polite"></ul>
                    <div data-kk-fast-search-result role="status" aria-live="polite"></div>
                    <p class="description"><?php esc_html_e('Closing this popup reloads the page so the index status shows the new state.', 'koperasikita'); ?></p>
                </div>
            </div>
        </div>
        <?php
        echo '</section>';
    }
}
